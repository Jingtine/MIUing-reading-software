const esbuild=require('esbuild');
const fs=require('node:fs');
const path=require('node:path');
const {boundMobi}=require('./bounds.cjs');
const root=path.resolve(__dirname,'../..');
const generated=path.join(__dirname,'.bounded-mobi.js');
fs.writeFileSync(generated,boundMobi(fs.readFileSync(path.join(root,'third_party/foliate-js/mobi.js'),'utf8')));
try {
esbuild.buildSync({
  entryPoints:[path.join(__dirname,'index.js')],bundle:true,format:'iife',target:'chrome69',
  outfile:path.join(root,'app/src/main/assets/book-import.js'),minify:true,legalComments:'inline',
  // Upstream sources are fixed; this generated input adds bounded decompression.
  alias:{'miuing-mobi':path.join(__dirname,'.bounded-mobi.js')},
  banner:{js:'/* MIUing import adapter; Foliate-js and fflate MIT notices: assets/licenses. Generated by tools/import-converter/build.cjs. */'},
});
} finally {fs.unlinkSync(generated);}
